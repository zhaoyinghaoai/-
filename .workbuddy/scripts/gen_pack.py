# -*- coding: utf-8 -*-
"""
军事文章「发文包」生成器
用法：python gen_pack.py <稿件md路径> <输出txt路径>

从稿件 md 里抽取：标题 / 标签 / 配图 / 正文 / 微头条 / 评论引导 / 检查清单，
拼成可直接照做的发布包。正文逐字抽取，保证 md 与 txt 一致。
"""
import re
import sys

MD = sys.argv[1] if len(sys.argv) > 1 else r'E:/北辰/浩总的个人知识库/产出/军事文章/胡塞通行证篇_v1_20260917.md'
OUT = sys.argv[2] if len(sys.argv) > 2 else r'E:/北辰/浩总的个人知识库/产出/军事文章/胡塞通行证篇_发文包_20260917.txt'

t = open(MD, encoding='utf-8').read()


def find(pat, default=''):
    m = re.search(pat, t, re.S)
    return m.group(1).strip() if m else default


# 标题：主推（第一个加粗引号标题）
title = find(r'### 🔴 主推[^\n]*\n\*\*`([^`]+)`\*\*')
# 备选标题（含"主推 B"这类第二主推，排除已作主标题的那条）
alts = [a for a in re.findall(r'### (?:(?:🔴\s*)?主推|备选)[^\n]*\n\*\*`([^`]+)`\*\*', t) if a != title]

# 标签（锚点用"章节号+关键词"，后缀放开，避免标题微调后静默抽空）
tags = find(r'## 八、标签建议\n+\*\*主推[^\n]*：\s*([^\n]+)')

# 正文
body_raw = find(r'## 五、正文\n\s*### .*?\n(.*?)\n---\n')
body_plain = re.sub(r'^#{3,6}\s*', '', body_raw, flags=re.M).replace('**', '')
wc = len(re.sub(r'\s', '', re.sub(r'[*#>]', '', body_raw)))

# 微头条（章节标题可能带后缀，如"（微头条 · 评论形态）"，故用宽松匹配）
micro = find(r'## 十、转发文案[^\n]*\n\s*```\n(.*?)```')

# 评论/回复（章节标题可能带后缀，锚点用"章节号+关键词"再接 [^\n]* 放开）
csec = find(r'## 十一、评论[^\n]*\n(.*?)\n---\n')
c_blocks = re.findall(r'```\n(.*?)```', csec, re.S)

# 检查清单
checklist = find(r'## 十二、发布前检查清单\n(.*?)$')

# 配图（表格 + 目录行，取到"### "小节前）
pic = find(r'## 九、配图方案[^\n]*\n(.*?)(?=\n### |\Z)')

out = f"""========================================
发布包 · {MD.split('/')[-1].replace('.md', '')}
平台：今日头条（微头条同步）
========================================

【一、标题】（主推）
------------------------------------------------
{title}

备选：
""" + '\n'.join(f'{chr(65+i)}. {a}' for i, a in enumerate(alts)) + f"""

【二、标签】（定 4 个，不是 5 个）
------------------------------------------------
{tags}

【三、配图】（已下载到本地，直接用）
------------------------------------------------
{pic}

【四、正文】（{wc} 字，可直接粘贴）
------------------------------------------------
{body_plain}

【五、微头条转发文案】（⚠️ 它同时就是评论区那条评论）
------------------------------------------------
{micro}

【六、评论区】（🔴 只发一条，不要另发自评）
------------------------------------------------
微头条转发会在原文章下面自动生成一条评论，它自己就是评论区那条评论。
再单独发自评 = 两条各自独立的评论并排，看起来很难看。

默认什么都不用做。若要补事实细节，用「回复」把下面这段挂在
自己那条转发评论下面（不是新发一条评论）：

""" + (c_blocks[0].strip() if c_blocks else '（无）') + (f"""

若读者来问（这是回复别人，正常发）：
{c_blocks[1].strip()}""" if len(c_blocks) > 1 else '') + f"""

【七、发布前检查清单】
------------------------------------------------
{checklist}

========================================
正文与 md 稿逐字一致 | 字数 {wc}
========================================
"""

open(OUT, 'w', encoding='utf-8').write(out)

chk = out.split('【四、正文】')[1].split('【五、')[0]
print('已生成：', OUT)
print('正文字数：', wc)
print('逐字一致：', body_plain in chk)
print('标题：', title)
print('标签：', tags or '⚠️ 未抽取到')
micro_len = len(re.sub(r'\s', '', micro))
print('微头条：', f'有（{micro_len} 字）' if micro else '⚠️ 未抽取到')
print('配图节：', '有' if pic else '⚠️ 未抽取到')
print('检查清单：', '有' if checklist else '⚠️ 未抽取到')
# 作废词扫描（派生文件核对铁律）
# 只扫「全局作废」的词：`军事观察` 已被品类大盘词 `军事`（40万 vs 3445）顶替，任何篇目都不该再挂。
# 注：`国际政治`／`红海` 是「本篇作废」而非全局作废——是否可用要看本篇槽位结构，
#     例如 3 个带量词已填满时功能槽才让位；冷池词（红海系）按带量词判据划掉。
#     这类词不在此扫描，避免误报。
STALE = ['军事观察']
hit = [w for w in STALE if w in tags]
print('全局作废标签残留：', hit if hit else '无 ✅')
